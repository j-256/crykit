import { expect, test } from '@playwright/test'
import { referencePath, referenceUrlPattern } from './reference-helpers'
import { MOBILE_TEST_TAG } from './test-tags'
import { expectOfflineReady } from './offline-helpers'

test('an item leads to its shop and required item, with usable mobile layout', { tag: MOBILE_TEST_TAG }, async ({ page, context }) => {
  await page.goto(referencePath('base:item:203'))
  const section = page.getByRole('region', { name: 'How to obtain', exact: true })
  await expect(section.getByRole('heading', { name: 'Buy', exact: true })).toBeVisible()
  await expect(section).toContainText('Dione Shrine')
  await expect(section.getByRole('img', { name: '60 silver', exact: true })).toBeVisible()
  await expect(section).toContainText('Understand Quintars')
  await section.getByRole('combobox', { name: 'Game mode', exact: true }).selectOption({ label: 'Vanilla' })
  await page.reload()
  await expect(section.getByRole('combobox', { name: 'Game mode', exact: true })).toHaveValue('vanilla')
  const prerequisite = section.getByRole('link', { name: 'Babel Quintar', exact: true })
  await expect(prerequisite).toBeVisible()
  const tab = await context.newPage()
  await tab.goto(await prerequisite.evaluate((link: HTMLAnchorElement) => link.href))
  await expect(tab.getByRole('region', { name: 'How to obtain', exact: true }).getByRole('combobox', { name: 'Game mode', exact: true })).toHaveValue('vanilla')
  await tab.close()
  await prerequisite.click()
  await expect(page).toHaveURL(referenceUrlPattern('base:item:167'))
  await expect(page.getByRole('region', { name: 'How to obtain', exact: true }).getByRole('combobox', { name: 'Game mode', exact: true })).toHaveValue('vanilla')
  await expect(page.getByRole('region', { name: 'How to obtain', exact: true }).getByRole('heading', { name: 'Find in a chest', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('an item leads to its monster source and preserves separate steal rates', async ({ page }) => {
  await page.goto(referencePath('base:item:18'))
  const section = page.getByRole('region', { name: 'How to obtain', exact: true })
  const slime = section.locator('.acquisition-route').filter({ has: page.getByRole('link', { name: 'Slime (level 3)', exact: true }) })
  await expect(slime.filter({ hasText: 'Base drop chance' })).toContainText('50%')
  await expect(slime.filter({ hasText: 'Steal success per attempt' })).toContainText('Availability: 75%')
  await expect(slime.filter({ hasText: 'Steal success per attempt' })).toContainText('60%')
  await slime.filter({ hasText: 'Base drop chance' }).getByRole('link', { name: 'Slime (level 3)', exact: true }).click()
  await expect(page).toHaveURL(referenceUrlPattern('base:monster:2'))
  await expect(page.getByRole('region', { name: 'Drops', exact: true }).getByRole('link', { name: 'Tonic', exact: true })).toBeVisible()
})

