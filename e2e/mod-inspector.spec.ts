test('retains a failed save for recovery and retries the same exact draft', async ({ page }) => {
  await page.addInitScript(() => {
    const originalPut = IDBObjectStore.prototype.put
    IDBObjectStore.prototype.put = function (...args: Parameters<typeof originalPut>) {
      const request = originalPut.apply(this, args)
      if (this.transaction.db.name === 'crykit-mod-inspector-v1' && sessionStorage.getItem('synthetic-reject-inspector-write') === 'true') this.transaction.abort()
      return request
    }
  })
  await importMod(page)
  await selectPath(page, '$.Title')
  await page.evaluate(() => sessionStorage.setItem('synthetic-reject-inspector-write', 'true'))
  await page.getByRole('textbox', { name: /^Exact JSON value/ }).fill('"Recoverable draft"')
  await page.getByRole('button', { name: 'Apply JSON edit', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Draft is not saved')
  expect(await downloadText(page, 'Download unsaved draft for recovery')).toBe(SOURCE.replace('"Synthetic inspector"', '"Recoverable draft"'))
  expect(await downloadText(page, 'Download original')).toBe(SOURCE)
  await page.evaluate(() => sessionStorage.removeItem('synthetic-reject-inspector-write'))
  await page.getByRole('button', { name: 'Retry save', exact: true }).click()
  await expect(page.getByText('Saved in this browser', { exact: true })).toBeVisible()
  await page.reload()
  await reopenFile(page)
  await expect(page.getByText('Saved in this browser', { exact: true })).toBeVisible()
  await selectPath(page, '$.Title')
  await expect(page.getByRole('textbox', { name: /^Exact JSON value/ })).toHaveValue('"Recoverable draft"')
})

test('reopens an edited document spanning storage chunks and preserves its exact original', async ({ page }) => {
  const payloadLength = 2 * 1024 * 1024 + 37
  const largeSource = SOURCE.replace('"FutureData": {', `"FutureData": {"payload": "${'x'.repeat(payloadLength)}", `)
  const expectedDraft = largeSource.replace('"Synthetic inspector"', '"Chunked draft"')
  const digest = (text: string) => createHash('sha256').update(text).digest('hex')
  await importMod(page, largeSource)
  await selectPath(page, '$.Title')
  await page.getByRole('textbox', { name: /^Exact JSON value/ }).fill('"Chunked draft"')
  await page.getByRole('button', { name: 'Apply JSON edit', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Select $.Title', exact: true })).toContainText('Chunked draft')
  await expect(page.getByText('Saved in this browser', { exact: true })).toBeVisible()
  await page.reload()
  await reopenFile(page)
  await expect(page.getByText('Saved in this browser', { exact: true })).toBeVisible()
  await selectPath(page, '$.Title')
  await expect(page.getByRole('textbox', { name: /^Exact JSON value/ })).toHaveValue('"Chunked draft"')
  await page.getByRole('button', { name: 'Review export', exact: true }).click()
  await expect(page.locator('.inspector-change')).toHaveCount(1)
  expect(digest(await downloadText(page, 'Download mod'))).toBe(digest(expectedDraft))
  expect(digest(await downloadText(page, 'Download original'))).toBe(digest(largeSource))
})

