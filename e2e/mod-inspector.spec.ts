import { expect, test, type Page } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import { expectOfflineReady } from './offline-helpers'

const ROUTE = '/#/mods/editor'
const FILENAME = 'synthetic-inspector.json'
const SOURCE = '\ufeff{\r\n  "EditorVersion": 34,\r\n  "Title": "Synthetic inspector",\r\n  "SteamWorkshopFileID": 9007199254740993,\r\n  "Passives": [{"ID": 91000, "Name": "Synthetic sight", "StatMods": [{"Tag": 9001, "Value1": 0, "Value2": 0, "Value3": 0}]}],\r\n  "Abilities": [{"ID": 92000, "Name": "Synthetic action"}],\r\n  "Jobs": [{"ID": 93000, "Name": "Synthetic job", "AbilityIDs": [92000]}],\r\n  "FutureData": {"nullValue": null, "text": "<script>throw new Error(1)</script>", "precise": 0.12345678901234567890123456789}\r\n}\r\n'

async function importMod(page: Page, source = SOURCE) {
  await page.goto(ROUTE)
  await page.getByLabel('Open mod JSON file', { exact: true }).setInputFiles({ name: FILENAME, mimeType: 'application/json', buffer: Buffer.from(source) })
  await expect(page.getByText('Saved in this browser', { exact: true })).toBeVisible()
}

async function reopenFile(page: Page) {
  const files = page.getByRole('combobox', { name: 'Files opened in this tool', exact: true })
  const option = files.locator('option').filter({ hasText: FILENAME })
  await expect(option).toHaveCount(1)
  await files.selectOption((await option.getAttribute('value'))!)
}

async function selectPath(page: Page, path: string, query = path) {
  await page.getByLabel('Search keys, values, and decoded names', { exact: true }).fill(query)
  await page.locator('.inspector-search-result').filter({ has: page.locator('code', { hasText: new RegExp(`^${path.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}$`) }) }).click()
  await expect(page.getByRole('textbox', { name: /^Exact JSON value/ })).toBeEnabled()
}

async function downloadText(page: Page, buttonName: string) {
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: buttonName, exact: true }).click()
  const result = await download
  return readFile((await result.path())!, 'utf8')
}

