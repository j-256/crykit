import { expect, test } from '@playwright/test'
import { createSaveEditorFixture } from '../../src/domain/save-editor.fixture'
import { encodeCrystalSave, decodeCrystalSave } from '../../src/interchange/crystal-save'

const GUEST_SECOND_IMPORT_READY_MS = 10_000
const ACCOUNT_SAVE_JOURNEY_MS = 180_000
const ACCOUNT_SAVE_IMPORT_READY_MS = 20_000
const ACCOUNT_SAVE_PENDING_READY_MS = 15_000
const ACCOUNT_SAVE_SYNC_READY_MS = 30_000
const ACCOUNT_SAVE_REMOTE_READY_MS = 60_000
const saveRoute = '/__accounts-proof/account-workspace.html#/save-editor'
const original = Buffer.from(encodeCrystalSave(createSaveEditorFixture()))
async function downloadBytes(download: import('@playwright/test').Download) {
  const stream = await download.createReadStream(), chunks: Buffer[] = []
  for await (const chunk of stream) chunks.push(Buffer.from(chunk))
  return Buffer.concat(chunks)
}
test('guest invalid pending input survives quiet save and reload without applying or downloading', async ({ page }) => {
  const downloads: string[] = []
  page.on('download', download => downloads.push(download.suggestedFilename()))
  await page.goto(saveRoute)
  await page.getByLabel('Open Crystal Project save', { exact: true }).setInputFiles({ name: 'original.sav', mimeType: 'application/octet-stream', buffer: original })
  const field = page.getByLabel('Copper', { exact: true })
  await field.fill('invalid first')
  await expect(page.getByRole('combobox', { name: 'Saved game saves', exact: true })).toBeEnabled()
  await field.fill('invalid second')
  await field.evaluate(element => (element as HTMLInputElement).setSelectionRange(2, 7, 'backward'))
  await expect(page.getByRole('combobox', { name: 'Saved game saves', exact: true })).toBeEnabled()
  await expect(field).toBeFocused()
  expect(await field.evaluate(element => [(element as HTMLInputElement).selectionStart, (element as HTMLInputElement).selectionEnd, (element as HTMLInputElement).selectionDirection])).toEqual([2, 7, 'backward'])
  expect(downloads).toEqual([])
  await page.reload()
  const files = page.getByRole('combobox', { name: 'Saved game saves', exact: true }), option = files.locator('option').filter({ hasText: 'original.sav' })
  await expect(option).toHaveCount(1)
  await files.selectOption((await option.getAttribute('value'))!)
  await expect(field).toHaveValue('invalid second')
  const pending = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export edited save', exact: true }).click()
  expect(await downloadBytes(await pending)).toEqual(original)
  await expect(page.getByText('Working download requested', { exact: false })).toBeVisible()
})
test('guest Apply persists working bytes and retains both originals when another unsupported save is imported', async ({ page }) => {
  await page.goto(saveRoute)
  await page.getByLabel('Open Crystal Project save', { exact: true }).setInputFiles({ name: 'first.sav', mimeType: 'application/octet-stream', buffer: original })
  await page.getByLabel('Copper', { exact: true }).fill('4321')
  await page.getByRole('button', { name: 'Apply currency', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Export edited save', exact: true })).toBeEnabled()
  let pending = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export edited save', exact: true }).click()
  expect(decodeCrystalSave(await downloadBytes(await pending)).header.currencyAmount).toBe(4321)
  await expect(page.getByRole('combobox', { name: 'Saved game saves', exact: true })).toBeEnabled()
  const unsupported = Buffer.from([99, 0, 255, 12])
  await page.getByLabel('Open Crystal Project save', { exact: true }).setInputFiles({ name: 'future.sav', mimeType: 'application/octet-stream', buffer: unsupported })
  await expect(page.getByText('Read-only save', { exact: true })).toBeVisible({ timeout: GUEST_SECOND_IMPORT_READY_MS })
  pending = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download original', exact: true }).click()
  expect(await downloadBytes(await pending)).toEqual(unsupported)
  const files = page.getByRole('combobox', { name: 'Saved game saves', exact: true })
  await expect(files.locator('option')).toHaveCount(3)
  await files.selectOption((await files.locator('option').filter({ hasText: 'first.sav' }).getAttribute('value'))!)
  await expect(page.getByLabel('Copper', { exact: true })).toHaveValue('4321')
  pending = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download original', exact: true }).click()
  expect(await downloadBytes(await pending)).toEqual(original)
})
test('account Save persists invalid input and exact bytes for a second browser', async ({ browser, baseURL }) => {
  test.setTimeout(ACCOUNT_SAVE_JOURNEY_MS)
  const contexts = await Promise.all([browser.newContext({ baseURL }), browser.newContext({ baseURL })])
  const [first, second] = await Promise.all(contexts.map(context => context.newPage()))
  const username = `save_${crypto.randomUUID().replaceAll('-', '').slice(0, 10)}`, email = `${username}@example.org`, password = 'synthetic durable save test password'
  try {
    await first.goto('/__accounts-proof/')
    await expect(first.locator('#status')).toHaveText('Browser worker and offline cache ready')
    await first.evaluate(input => (window as unknown as { accountAuth: typeof import('../../src/account/auth-client') }).accountAuth.registerAccount(input), { email, username, password, remember: false })
    await first.request.post('/__accounts/jobs')
    const emails = await (await first.request.get('/__accounts/emails')).json() as { recipient: string; capability: string }[]
    await first.evaluate(capability => fetch('/api/v1/auth/verify', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ capability }) }), emails.find(row => row.recipient === email)!.capability)
    for (const page of [first, second]) {
      await page.goto('/__accounts-proof/account-workspace.html#/settings/account')
      await page.getByLabel('Email', { exact: true }).fill(email)
      await page.getByLabel('Password', { exact: true }).fill(password)
      await page.getByRole('button', { name: 'Sign in', exact: true }).click()
      await page.getByRole('button', { name: 'Open account workspace', exact: true }).click()
      await expect(page.getByRole('heading', { name: 'Builds', exact: true })).toBeVisible()
      await page.evaluate(() => { window.location.hash = '#/save-editor' })
      await expect(page.getByRole('heading', { name: 'Save Editor', exact: true })).toBeVisible()
    }
    await first.getByLabel('Open Crystal Project save', { exact: true }).setInputFiles({ name: 'private.sav', mimeType: 'application/octet-stream', buffer: original })
    await expect(first.getByLabel('Copper', { exact: true })).toBeEnabled({ timeout: ACCOUNT_SAVE_IMPORT_READY_MS })
    await first.getByLabel('Copper', { exact: true }).fill('private invalid currency')
    await expect(first.getByRole('combobox', { name: 'Saved game saves', exact: true })).toBeEnabled({ timeout: ACCOUNT_SAVE_PENDING_READY_MS })
    await expect(first.getByRole('complementary', { name: 'Account sync' }).getByRole('status')).toHaveText('Synced', { timeout: ACCOUNT_SAVE_SYNC_READY_MS })
    const files = second.getByRole('combobox', { name: 'Saved game saves', exact: true }), option = files.locator('option').filter({ hasText: 'private.sav' })
    await expect(option).toHaveCount(1)
    await second.bringToFront()
    await expect(option).toHaveAttribute('data-revision', '2', { timeout: ACCOUNT_SAVE_REMOTE_READY_MS })
    await files.selectOption((await option.getAttribute('value'))!)
    await expect(second.getByLabel('Copper', { exact: true })).toHaveValue('private invalid currency')
    const content = await second.evaluate(() => (window as unknown as { workspaceProof: { saveContent(): Promise<{ original: number[]; working: number[] }[]> } }).workspaceProof.saveContent())
    expect(content[0].original).toEqual([...original])
    expect(content[0].working).toEqual([...original])
  } finally { await Promise.all(contexts.map(context => context.close())) }
})

test('guest Save reopens offline on mobile with invalid input and exact original bytes', async ({ page, context }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.emulateMedia({ colorScheme: 'dark' })
  await page.goto('/__accounts-proof/')
  await expect(page.locator('#status')).toHaveText('Browser worker and offline cache ready')
  await page.goto(saveRoute)
  await page.getByLabel('Open Crystal Project save', { exact: true }).setInputFiles({ name: 'offline.sav', mimeType: 'application/octet-stream', buffer: original })
  await page.getByLabel('Copper', { exact: true }).fill('offline invalid value')
  await expect(page.getByRole('combobox', { name: 'Saved game saves', exact: true })).toBeEnabled()
  await context.setOffline(true)
  try {
    await page.reload()
    const files = page.getByRole('combobox', { name: 'Saved game saves', exact: true })
    const option = files.locator('option').filter({ hasText: 'offline.sav' })
    await expect(option).toHaveCount(1)
    await files.selectOption((await option.getAttribute('value'))!)
    await expect(page.getByLabel('Copper', { exact: true })).toHaveValue('offline invalid value')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await page.emulateMedia({ colorScheme: 'light' })
    const pending = page.waitForEvent('download')
    await page.getByRole('button', { name: 'Download original', exact: true }).click()
    expect(await downloadBytes(await pending)).toEqual(original)
    await expect(page.getByText('No working download recorded', { exact: false })).toBeVisible()
  } finally { await context.setOffline(false) }
})
