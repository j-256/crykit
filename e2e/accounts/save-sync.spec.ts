test('guest strict recovery preserves later input until an explicit confirmed reload', async ({ page }) => {
  await page.goto(saveRoute)
  await page.getByLabel('Open Crystal Project save', { exact: true }).setInputFiles({ name: 'recover.sav', mimeType: 'application/octet-stream', buffer: original })
  await page.getByLabel('Copper', { exact: true }).fill('4321')
  await page.evaluate(() => (window as unknown as { workspaceProof: { armSaveStrictRecovery(): void } }).workspaceProof.armSaveStrictRecovery())
  await page.getByRole('button', { name: 'Apply currency', exact: true }).click()
  const recovery = page.getByRole('region', { name: 'Save recovery', exact: true })
  await expect(recovery.getByRole('button', { name: 'Download recovery copy' })).toBeEnabled()
  await expect(recovery.getByRole('button', { name: 'Retry operation' })).toHaveCount(0)
  page.once('dialog', dialog => dialog.dismiss())
  await recovery.getByRole('button', { name: 'Discard open form and reload' }).click()
  await expect(recovery.getByRole('button', { name: 'Discard open form and reload' })).toBeEnabled()
  const diagnostics = () => page.evaluate(() => (window as unknown as { workspaceProof: { saveDiagnostics(): { dirty: boolean; phase: string } } }).workspaceProof.saveDiagnostics())
  expect(await diagnostics()).toMatchObject({ dirty: true, phase: 'recovery' })
  page.once('dialog', dialog => dialog.accept())
  await recovery.getByRole('button', { name: 'Discard open form and reload' }).click()
  const files = page.getByRole('combobox', { name: 'Saved game saves', exact: true })
  const option = files.locator('option').filter({ hasText: 'recover.sav' })
  await expect(option).toHaveCount(1)
  await files.selectOption((await option.getAttribute('value'))!)
  await expect(page.getByLabel('Copper', { exact: true })).toHaveValue('4321')
  expect(await diagnostics()).toMatchObject({ dirty: false, phase: 'idle' })
  const pending = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download original', exact: true }).click()
  expect(await downloadBytes(await pending)).toEqual(original)
})

test('Save controls remain named and keyboard reachable with a long filename at both breakpoints and OS color preferences', async ({ page }, testInfo) => {
  const filename = `${'LongSyntheticFilename'.repeat(8)}.sav`
  await page.goto(saveRoute)
  await page.getByLabel('Open Crystal Project save', { exact: true }).setInputFiles({ name: filename, mimeType: 'application/octet-stream', buffer: original })
  const copper = page.getByLabel('Copper', { exact: true })
  await copper.focus(); await copper.fill('invalid keyboard input')
  await expect(copper).toHaveAttribute('aria-invalid', 'true')
  await expect(page.getByRole('combobox', { name: 'Saved game saves', exact: true })).toBeEnabled()
  await copper.press('Tab')
  await expect(page.getByRole('button', { name: 'Apply currency', exact: true })).toBeFocused()
  await page.getByRole('button', { name: 'Download original', exact: true }).focus()
  const pending = page.waitForEvent('download')
  await page.keyboard.press('Enter')
  expect(await downloadBytes(await pending)).toEqual(original)
  for (const width of [1440, 390]) for (const colorScheme of ['light', 'dark'] as const) {
    await page.setViewportSize({ width, height: 900 }); await page.emulateMedia({ colorScheme })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await expect(page.getByRole('combobox', { name: 'Saved game saves', exact: true }).locator('option').filter({ hasText: filename })).toHaveCount(1)
    await expect(copper).toHaveValue('invalid keyboard input')
    const screenshot = testInfo.outputPath(`save-${width}-${colorScheme}.png`)
    await page.screenshot({ path: screenshot, fullPage: true })
    await testInfo.attach(`save-${width}-${colorScheme}`, { path: screenshot, contentType: 'image/png' })
    expect(await page.locator('button:visible').evaluateAll(buttons => buttons.filter(button => !button.textContent?.trim() && !button.getAttribute('aria-label') && !button.getAttribute('aria-labelledby')).length)).toBe(0)
  }
})
