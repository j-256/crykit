import { expect, test, type Page } from '@playwright/test'
import { chooseTeamCheckpoint } from '../team-helpers'
import type { LocalData, TeamRevision } from '../../src/domain/types'
import { SYNTHETIC_LIBRARY_ROOTS } from '../mod-library-fixtures'

type Proof = { teamState(): Promise<LocalData>; seedTeamFixture(account?: boolean): Promise<void>; buildInputState(): { dirty: boolean; pending: string; values: Record<string, unknown> } }
const state = (page: Page) => page.evaluate(() => (window as unknown as { workspaceProof: Proof }).workspaceProof.teamState())
const owned = (data: LocalData, title: string): TeamRevision => { const team = Object.values(data.teams).find(value => value.title === title)!; if (team.kind !== 'shared') throw new Error('Expected shared'); return data.teamRevisions[team.latestRevisionId]! }
const app = '/__accounts-proof/account-workspace.html'
async function seedGuest(page: Page) {
  await page.goto(`${app}#/teams`)
  await expect(page.getByRole('heading', { name: 'Teams', exact: true })).toBeVisible()
  await page.evaluate(() => (window as unknown as { workspaceProof: Proof }).workspaceProof.seedTeamFixture())
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Teams', exact: true })).toBeVisible()
}
async function teamJourney(page: Page) {
  const before = await state(page)
  await page.getByRole('button', { name: 'New Team', exact: true }).click()
  await page.getByRole('textbox', { name: 'Team name', exact: true }).fill('Owned Team journey')
  await expect(page.getByRole('button', { name: 'Create member', exact: true }).first()).toBeDisabled()
  await page.getByRole('combobox', { name: /^Choose shared setup/ }).selectOption('gameSetup-revision')
  for (let slot = 1; slot <= 4; slot++) await chooseTeamCheckpoint(page, slot, 'Synthetic source-revision')
  await page.getByRole('button', { name: 'Save Team', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Owned Team journey', exact: true })).toBeVisible()
  const first = await state(page)
  expect(first.builds).toEqual(before.builds); expect(first.buildRevisions).toEqual(before.buildRevisions)
  const firstRevision = owned(first, 'Owned Team journey')
  await page.getByRole('button', { name: 'Edit Team', exact: true }).click()
  await page.getByRole('region', { name: 'Team slot 1 loadout', exact: true }).getByRole('button', { name: 'Edit member', exact: true }).click()
  await expect(page.getByLabel('Build title', { exact: true })).toHaveCount(0)
  await expect(page.getByText('Shared Team Game Setup:', { exact: false })).toBeVisible()
  await page.getByRole('button', { name: 'Checks & notes', exact: true }).click()
  await page.getByLabel('Rotation or use notes').fill('Owned member content changed')
  await page.getByRole('button', { name: 'Save member and return to Team', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Team name', exact: true })).toHaveValue('Owned Team journey')
  const edited = await state(page), editRevision = owned(edited, 'Owned Team journey')
  expect(editRevision.id).not.toBe(firstRevision.id)
  expect(editRevision.slots[0]!.content.rotationNotes).toBe('Owned member content changed')
  expect(editRevision.slots[1]!.content).toEqual(firstRevision.slots[1]!.content)
  expect(edited.builds).toEqual(before.builds); expect(edited.buildRevisions).toEqual(before.buildRevisions)
  await page.getByRole('button', { name: 'Move slot 2 left', exact: true }).click()
  await page.getByRole('combobox', { name: /^Choose shared setup/ }).selectOption('other-team-setup')
  await page.getByRole('button', { name: 'Save Team', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Team checkpoint history' })).toContainText('Other shared rules')
  const changed = await state(page), changedRevision = owned(changed, 'Owned Team journey')
  expect(changedRevision.slots[1]!.content.rotationNotes).toBe('Owned member content changed')
  expect(changed.teamRevisions[firstRevision.id]).toEqual(firstRevision)
  expect(changed.playthroughs).toEqual(before.playthroughs)
  await page.getByText('Compare all four slots with previous checkpoint', { exact: true }).click()
  await expect(page.locator('.team-checkpoint-comparison')).toHaveCount(4)
  await page.getByRole('combobox', { name: 'Team checkpoint', exact: true }).selectOption(firstRevision.id)
  await expect(page.getByRole('region', { name: 'Team checkpoint history' })).toContainText('Verified test Game Setup')
  await page.getByRole('combobox', { name: 'Team checkpoint', exact: true }).selectOption(changedRevision.id)
  await page.getByRole('button', { name: 'Save slot 2 as Build', exact: true }).click()
  await expect.poll(async () => Object.values((await state(page)).builds).some(build => build.title === 'Owned Team journey - member 2')).toBe(true)
  const copied = await state(page), copy = Object.values(copied.builds).find(build => !before.builds[build.id])!
  expect(copied.buildRevisions[copy.latestRevisionId!]!.content).toEqual(changedRevision.slots[1]!.content)
  for (const [id, build] of Object.entries(before.builds)) expect(copied.builds[id]).toEqual(build)
  for (const [id, revision] of Object.entries(before.buildRevisions)) expect(copied.buildRevisions[id]).toEqual(revision)
  await page.getByRole('button', { name: 'Adopt Team', exact: true }).click()
  const characters = Object.values(before.playthroughs[before.selectedPlaythroughId!]!.characters)
  for (let slot = 1; slot <= 4; slot++) await page.getByRole('combobox', { name: `Tracked character ${slot}`, exact: true }).selectOption(characters[slot - 1]!.id)
  await page.getByLabel('I applied these builds in game').check()
  await page.getByRole('button', { name: 'Record Team as current', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Characters', exact: true })).toBeVisible()
  const adopted = await state(page), party = adopted.playthroughs[before.selectedPlaythroughId!]!
  const scenario = Object.values(party.scenarios).find(value => value.kind === 'recordedCurrent')!
  expect(scenario.gameSetupRevisionId).toBe(changedRevision.gameSetupRevisionId)
  expect(scenario.assignments[characters[0]!.id]).toEqual({ kind: 'team-slot', teamRevisionId: changedRevision.id, slot: 0 })
  expect(adopted.builds).toEqual(copied.builds); expect(adopted.buildRevisions).toEqual(copied.buildRevisions)
  expect(party.inventory).toEqual(before.playthroughs[before.selectedPlaythroughId!]!.inventory)
  for (const character of characters) expect(party.characters[character.id]!.learnedNodes).toEqual(character.learnedNodes)
  await page.reload()
  await expect.poll(() => page.evaluate(() => typeof (window as unknown as { workspaceProof?: Proof }).workspaceProof?.teamState)).toBe('function')
  expect((await state(page)).teamRevisions[changedRevision.id]).toEqual(changedRevision)
}

test('guest edits shared Team content, compares history, saves an independent Build and adopts into a Playthrough', async ({ page }) => {
  await seedGuest(page)
  await teamJourney(page)
})

test('encrypted account uses the same real Team editing and adoption journey', async ({ page }) => {
  await page.goto('/__accounts-proof/')
  await expect(page.locator('#status')).toHaveText('Browser worker and offline cache ready')
  const username = `team_${crypto.randomUUID().replaceAll('-', '').slice(0, 10)}`, email = `${username}@example.org`, password = 'synthetic team journey password'
  await page.evaluate(input => (window as unknown as { accountAuth: typeof import('../../src/account/auth-client') }).accountAuth.registerAccount(input), { email, username, password, remember: false })
  await page.request.post('/__accounts/jobs')
  const emails = await (await page.request.get('/__accounts/emails')).json() as { recipient: string; capability: string }[]
  await page.evaluate(capability => fetch('/api/v1/auth/verify', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ capability }) }), emails.find(value => value.recipient === email)!.capability)
  await page.goto(`${app}#/settings/account`)
  await page.getByLabel('Email', { exact: true }).fill(email); await page.getByLabel('Password', { exact: true }).fill(password)
  await page.locator('form').filter({ has: page.getByRole('button', { name: 'Sign in', exact: true }) }).getByLabel('Remember this device', { exact: true }).check()
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Open account workspace', exact: true })).toBeVisible()
  await page.evaluate(() => (window as unknown as { accountBootstrapProof: Proof }).accountBootstrapProof.seedTeamFixture(true))
  await page.getByRole('button', { name: 'Open account workspace', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Builds', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Teams', exact: true }).click()
  await teamJourney(page)
})

test('unsaved Team and member survive exact source import without implicit Save; cancellation preserves all saved records', async ({ page }) => {
  await seedGuest(page)
  const before = await state(page)
  await page.getByRole('button', { name: 'New Team', exact: true }).click()
  await page.getByRole('textbox', { name: 'Team name', exact: true }).fill('  Unsaved Team name  ')
  await page.getByRole('combobox', { name: /^Choose shared setup/ }).selectOption('gameSetup-revision')
  await chooseTeamCheckpoint(page, 1, 'Synthetic source-revision')
  await page.getByRole('region', { name: 'Team slot 1 loadout', exact: true }).getByRole('button', { name: 'Edit member', exact: true }).click()
  await page.getByRole('button', { name: 'Checks & notes', exact: true }).click()
  await page.getByLabel('Rotation or use notes').fill('Exact unfinished notes  ')
  await page.getByRole('button', { name: 'Loadout', exact: true }).click()
  await page.getByRole('combobox', { name: 'Class', exact: true }).click()
  await page.getByLabel('Import Build mod JSON', { exact: true }).setInputFiles({ name: 'team-source.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({ ...SYNTHETIC_LIBRARY_ROOTS[1], ID: 'team-source-import', Title: 'Team import source' })) })
  await expect(page.getByRole('region', { name: 'Import Build mod choices' })).toBeVisible()
  const formBefore = await page.evaluate(() => (window as unknown as { workspaceProof: Proof }).workspaceProof.buildInputState())
  expect(formBefore.dirty).toBe(true)
  await page.getByRole('button', { name: 'Add mod JSON', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Save member and return to Team', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Checks & notes', exact: true }).click()
  await expect(page.getByLabel('Rotation or use notes')).toHaveValue('Exact unfinished notes  ')
  expect(await page.evaluate(() => (window as unknown as { workspaceProof: Proof }).workspaceProof.buildInputState())).toEqual(formBefore)
  const imported = await state(page)
  expect(imported.gameSetups).toEqual(before.gameSetups)
  expect(imported.playthroughs).toEqual(before.playthroughs)
  expect(imported.teams).toEqual(before.teams); expect(imported.teamRevisions).toEqual(before.teamRevisions)
  expect(imported.builds).toEqual(before.builds); expect(imported.buildRevisions).toEqual(before.buildRevisions)
  await page.getByRole('button', { name: 'Cancel and return to Team', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Team name', exact: true })).toHaveValue('  Unsaved Team name  ')
  expect((await page.evaluate(() => (window as unknown as { workspaceProof: Proof }).workspaceProof.buildInputState())).dirty).toBe(true)
  await expect(page.getByRole('button', { name: 'Choose checkpoint for Team slot 1', exact: true })).toHaveAttribute('data-revision-id', 'Synthetic source-revision')
  await page.getByRole('button', { name: 'Discard and return', exact: true }).click()
  expect((await state(page)).teams).toEqual(before.teams)
  await page.getByRole('button', { name: 'Mods', exact: true }).click()
  const source = page.getByRole('region', { name: 'Team import source', exact: true })
  await expect(source).toContainText('Imported JSON')
  await expect(source.getByRole('button', { name: 'Add to Reference', exact: true })).toBeVisible()
})

for (const [id, title] of [['legacy', 'Legacy empty Team'], ['mixed', 'Legacy mixed Team']]) test(`${title} requires an explicit shared setup and preserves its original sources`, async ({ page }) => {
  await seedGuest(page)
  const before = await state(page)
  await page.locator('.team-list-card').filter({ has: page.getByRole('heading', { name: title, exact: true }) }).getByRole('button', { name: 'Open Team', exact: true }).click()
  await page.getByRole('button', { name: 'Edit Team', exact: true }).click()
  const setup = page.getByRole('combobox', { name: /^Choose shared setup/ })
  await expect(setup).toHaveValue('')
  await expect(page.getByRole('button', { name: 'Save Team', exact: true })).toBeDisabled()
  expect((await state(page)).teams[id!]).toEqual(before.teams[id!])
  await setup.selectOption('other-team-setup')
  await page.getByRole('button', { name: 'Save Team', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Team checkpoint history' })).toContainText('Other shared rules')
  const after = await state(page), checkpoint = owned(after, title!)
  const original = before.teams[id!]!
  if (original.kind !== 'legacy-mixed') throw new Error('Expected legacy fixture')
  expect(checkpoint.slots.map(slot => slot?.sourceBuildRevisionId ?? null)).toEqual(original.slots)
  expect(after.builds).toEqual(before.builds); expect(after.buildRevisions).toEqual(before.buildRevisions)
  expect(after.playthroughs).toEqual(before.playthroughs)
})
