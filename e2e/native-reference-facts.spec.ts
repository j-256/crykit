import { expect, test } from '@playwright/test'
import { referencePath, referenceUrlPattern } from './reference-helpers'
import { CONFLICTING_LOCATIONS, IMPORTED_DESCRIPTION, ORIGINAL_EFFECTS, REFERENCE_EVIDENCE_ENTITIES, REFERENCE_EVIDENCE_SOURCES, evidenceReferencePath, installReferenceEvidence } from './reference-evidence-fixtures'
import { MOBILE_TEST_TAG } from './test-tags'

test('Eclipse explains Blind as an on-hit effect in its page and result card', { tag: MOBILE_TEST_TAG }, async ({ page }) => {
  await page.goto(referencePath('base:equipment:41'))
  const effect = 'On hit, inflict: Blind for 1 turn (10% chance). Blind effect: Always miss physical attacks.'
  await expect(page.locator('.reference-detail .reference-description > p')).toContainText(effect)
  await page.getByRole('button', { name: 'Back to results', exact: true }).click()
  await page.getByRole('searchbox', { name: 'Search reference', exact: true }).fill('Eclipse')
  const result = page.getByRole('link').filter({ has: page.getByRole('heading', { name: 'Eclipse', exact: true }) })
  await expect(result).toContainText(effect)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('native effects remain separate from preserved imported original claims', { tag: MOBILE_TEST_TAG }, async ({ page }) => {
  await installReferenceEvidence(page)
  await page.goto(referencePath('base:item:132'))
  await expect(page.locator('.reference-detail .reference-description')).toContainText(/100% Missing HP/i)
  await expect(page.locator('.reference-detail .reference-description')).not.toContainText('Recovery: 100% HP')
  const facts = page.getByRole('region', { name: 'Definition facts', exact: true })
  await expect(facts).not.toContainText('Sources differ')
  await expect(facts.locator('dt').filter({ hasText: /^Effect$/ })).toHaveCount(0)
  await page.goto(evidenceReferencePath(REFERENCE_EVIDENCE_ENTITIES.effects))
  await page.getByRole('button', { name: 'Sources for Synthetic original effects', exact: true }).click()
  const originals = page.getByRole('region', { name: 'Imported claims', exact: true })
  for (const effect of ORIGINAL_EFFECTS) await expect(originals.getByText(effect, { exact: true })).toBeVisible()
  for (const source of REFERENCE_EVIDENCE_SOURCES) await expect(originals.locator(`a[href="${source.sourceId}"]`)).toHaveCount(1)
  await page.keyboard.press('Escape')
  await page.reload()
  for (const effect of ORIGINAL_EFFECTS) await expect(facts.getByText(effect, { exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('native effects stay quiet while retained route guidance cites its own source', { tag: MOBILE_TEST_TAG }, async ({ page }) => {
  await page.goto(referencePath('base:equipment:134'))
  await expect(page.getByRole('region', { name: 'Game details', exact: true })).toHaveCount(0)
  const description = page.locator('.reference-detail .reference-description')
  await expect(description.locator(':scope > p')).toContainText(/Resistance:\s*\+78/)
  await expect(description.locator(':scope > p')).toContainText(/Max\. MP:\s*\+20/)
  await expect(description.locator(':scope > p')).toContainText('Take 5% less magical damage.')
  await expect(description.getByRole('button', { name: 'Sources for Description', exact: true })).toHaveCount(0)
  const facts = page.getByRole('region', { name: 'Definition facts', exact: true })
  const type = facts.locator('.definition-row').filter({ has: page.getByText('Equipment Type', { exact: true }) })
  await expect(type).toContainText('Light armor')
  await expect(type.locator('.sources-trigger')).toHaveCount(0)
  await expect(facts.locator('dt').filter({ hasText: /^Type$/ })).toHaveCount(0)
  const mp = facts.locator('.definition-row').filter({ has: page.locator('dt').filter({ hasText: /^Max MP$/ }) })
  await expect(mp.locator('dd')).toHaveText('20')
  await expect(mp.locator('.sources-trigger')).toHaveCount(0)
  await expect(facts.locator('dt').filter({ hasText: /^(Stat|Stat bonuses|Effect|Other effects)$/ })).toHaveCount(0)
  await page.goto(referencePath('base:item:22'))
  await expect(description).toContainText('teleports the party to the roof of the Gaea Shrine')
  await description.getByRole('button', { name: 'Sources for Description', exact: true }).click()
  const sources = page.getByRole('dialog', { name: 'Sources for Description', exact: true })
  await expect(sources.locator('a[href="https://crystal-project.fandom.com/wiki/Gaea_Shard?oldid=7599"]')).toBeVisible()
  await expect(sources).toContainText('CC-BY-SA')
  await expect(sources).not.toContainText('Native game data')
})

test('equal recipe names keep independent imported and native identities through navigation', async ({ page }) => {
  await installReferenceEvidence(page)
  const importedPath = evidenceReferencePath(REFERENCE_EVIDENCE_ENTITIES.recipe)
  await page.goto(importedPath)
  await expect(page.getByRole('heading', { name: 'Fursuit', exact: true })).toBeVisible()
  await expect(page.getByRole('region', { name: 'Definition facts', exact: true })).toContainText('Synthetic recipe from an independent source')
  expect(new URL(page.url()).hash).toBe(new URL(importedPath, page.url()).hash)
  await page.getByRole('button', { name: 'Sources for Fursuit', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Sources for Fursuit', exact: true }).locator(`a[href="${REFERENCE_EVIDENCE_SOURCES[0]!.sourceId}"]`)).toBeVisible()
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Back to results', exact: true }).click()
  await page.getByRole('searchbox', { name: 'Search reference', exact: true }).fill('Fursuit')
  const nativeRecipe = page.locator(`.reference-card[href^="${referencePath('base:recipe:36').slice(1)}"]`).filter({ has: page.getByRole('heading', { name: 'Fursuit', exact: true }) })
  expect(await nativeRecipe.evaluate((link: HTMLAnchorElement) => link.href)).toMatch(referenceUrlPattern('base:recipe:36'))
  await expect(nativeRecipe).toHaveCount(1)
  await nativeRecipe.click()
  await expect(page).toHaveURL(referenceUrlPattern('base:recipe:36'))
  await expect(page.getByRole('region', { name: 'Definition facts', exact: true })).not.toContainText('Synthetic recipe from an independent source')
  await page.goto(importedPath)
  await page.reload()
  await expect(page.getByRole('region', { name: 'Definition facts', exact: true })).toContainText('Synthetic recipe from an independent source')
})

test('imported acquisition disagreements remain visible independently of native routes', async ({ page }) => {
  await installReferenceEvidence(page)
  await page.goto(referencePath('base:item:18'))
  await expect(page.getByRole('region', { name: 'How to obtain', exact: true })).toContainText('Steal')
  await expect(page.getByRole('region', { name: 'How to obtain', exact: true })).toContainText('Slime')
  await page.goto(evidenceReferencePath(REFERENCE_EVIDENCE_ENTITIES.conflicting))
  const facts = page.getByRole('region', { name: 'Definition facts', exact: true })
  for (const location of CONFLICTING_LOCATIONS) await expect(facts).toContainText(location)
  await expect(facts).toContainText('2 differing source values')
  await page.getByRole('button', { name: 'Sources for Synthetic disputed seal', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Imported claims', exact: true })).toContainText(CONFLICTING_LOCATIONS[1])
  await page.keyboard.press('Escape')
  await page.goto(referencePath('base:item:18'))
  await page.getByRole('combobox', { name: 'Game mode', exact: true }).selectOption('chaos')
  await page.goto(evidenceReferencePath(REFERENCE_EVIDENCE_ENTITIES.conflicting))
  for (const location of CONFLICTING_LOCATIONS) await expect(facts).toContainText(location)
})

test('changing native acquisition mode does not rewrite independent imported notes', async ({ page }) => {
  await installReferenceEvidence(page)
  await page.goto(referencePath('base:equipment:134'))
  const acquisition = page.getByRole('region', { name: 'How to obtain', exact: true })
  await acquisition.getByRole('combobox', { name: 'Game mode', exact: true }).selectOption('vanilla')
  await expect(acquisition).toContainText('Reward: talk to mushroom in Quintar Sanctum')
  await acquisition.getByRole('combobox', { name: 'Game mode', exact: true }).selectOption('chaos')
  await expect(acquisition).not.toContainText('Reward: talk to mushroom in Quintar Sanctum')
  await page.goto(evidenceReferencePath(REFERENCE_EVIDENCE_ENTITIES.description))
  await expect(page.locator('.reference-description')).toContainText(IMPORTED_DESCRIPTION)
  await page.reload()
  await expect(page.locator('.reference-description')).toContainText(IMPORTED_DESCRIPTION)
})

test('external descriptions cite their own text without duplicating matching fact markers', async ({ page }) => {
  await installReferenceEvidence(page)
  await page.goto(evidenceReferencePath(REFERENCE_EVIDENCE_ENTITIES.description))
  const hero = page.locator('.reference-description')
  await expect(hero).toContainText(IMPORTED_DESCRIPTION)
  await expect(hero.getByRole('button', { name: 'Sources for Description', exact: true })).toHaveCount(1)
  await expect(page.getByRole('region', { name: 'Definition facts', exact: true }).locator('dt').filter({ hasText: /^Description$/ })).toHaveCount(0)
  await hero.getByRole('button', { name: 'Sources for Description', exact: true }).click()
  const popup = page.getByRole('dialog', { name: 'Sources for Description', exact: true })
  await expect(popup.locator(`a[href="${REFERENCE_EVIDENCE_SOURCES[0]!.sourceId}"]`)).toBeVisible()
  await expect(popup).toContainText('revision 12')
  await expect(popup).not.toContainText('base database')
})
