it('keeps the independent progress capability in a header and clears active keys only after acceptance',async()=>{
  const {deleteAccount,readDeletionStatus}=await import('../../account/deletion')
  const key=new Uint8Array(32).fill(9),token=profile.installProfile('account',key,{accountId:'account',sessionId:'session',deviceId:'device',csrf:'csrf',username:'user',authenticatedAt:Date.now()})
  const calls:{url:string;init?:RequestInit}[]=[]
  vi.spyOn(globalThis,'fetch').mockImplementation(async(url,init)=>{calls.push({url:String(url),init});return Response.json({state:'pending',phase:'ledger'})})
  expect(await deleteAccount(token,'DELETE MY ACCOUNT')).toEqual({state:'pending',phase:'ledger'})
  expect(profile.currentProfileToken()).toBeUndefined()
  expect([...key]).toEqual(Array(32).fill(0))
  const capability=new Headers(calls[0].init?.headers).get('x-deletion-status')!
  expect(capability).toHaveLength(43)
  expect(calls[0].url).toBe('/api/v1/account/deletion')
  expect(calls[0].init?.body).toBe(JSON.stringify({confirmation:'DELETE MY ACCOUNT'}))
  expect(String(calls[0].init?.body)).not.toContain(capability)
  await readDeletionStatus()
  expect(new Headers(calls[1].init?.headers).get('x-deletion-status')).toBe(capability)
  expect(calls[1].init?.body).toBeUndefined()
  expect(calls[1].url).not.toContain(capability)
})
it('retains uncertain deletion progress across reload-style reads without clearing a successor profile',async()=>{
  const {deleteAccount,readDeletionStatus,hasDeletionStatus}=await import('../../account/deletion')
  const token=profile.installProfile('old',new Uint8Array(32),{accountId:'old',sessionId:'session',deviceId:'device',csrf:'csrf',username:'user',authenticatedAt:Date.now()})
  let release!:(value:Response)=>void
  vi.spyOn(globalThis,'fetch').mockImplementationOnce(()=>new Promise(resolve=>{release=resolve})).mockResolvedValue(Response.json({state:'pending',phase:'fence'}))
  const pending=deleteAccount(token,'DELETE MY ACCOUNT').catch(error=>error)
  profile.invalidateProfile()
  const successor=profile.installProfile('new',new Uint8Array(32))
  release(Response.json({state:'pending',phase:'ledger'}))
  expect(await pending).toBeInstanceOf(profile.ProfileChangedError)
  expect(profile.currentProfileToken()).toBe(successor)
  expect(hasDeletionStatus()).toBe(true)
  expect(await readDeletionStatus()).toEqual({state:'pending',phase:'fence'})
})
