it('retries a before-delivery failure with the retained grant and original account after status404',async()=>{
  const {deleteAccount,retryDeletion,hasDeletionStatus}=await import('../../account/deletion')
  const token=profile.installProfile('original',new Uint8Array(32),{accountId:'original',sessionId:'session',deviceId:'device',csrf:'csrf',username:'user',authenticatedAt:Date.now()})
  const fetch=vi.spyOn(globalThis,'fetch').mockRejectedValueOnce(new TypeError('offline'))
  await expect(deleteAccount(token,'DELETE MY ACCOUNT')).rejects.toThrow('offline')
  const capability=new Headers(fetch.mock.calls[0][1]?.headers).get('x-deletion-status')
  fetch.mockResolvedValueOnce(Response.json({error:{code:'NOT_FOUND',requestId:'fixture'}},{status:404})).mockResolvedValueOnce(Response.json({state:'pending',phase:'ledger'}))
  expect(await retryDeletion(token,'DELETE MY ACCOUNT')).toEqual({state:'pending',phase:'ledger'})
  expect(fetch.mock.calls[1][1]?.method).toBeUndefined()
  expect(fetch.mock.calls[2][1]?.method).toBe('POST')
  expect(new Headers(fetch.mock.calls[2][1]?.headers).get('x-deletion-status')).toBe(capability)
  expect(fetch.mock.calls[2][1]?.body).toBe(JSON.stringify({confirmation:'DELETE MY ACCOUNT'}))
  expect(hasDeletionStatus()).toBe(true)
  expect(profile.currentProfileToken()).toBeUndefined()
})
