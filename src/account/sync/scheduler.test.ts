  const calls: number[] = []
  let state = '', progress = true
  attachSyncScheduler(token, async () => { calls.push(Date.now()); if (progress) throw new CommitProgress(10_000); throw new SyncError('SERVICE_UNAVAILABLE', 10_000) })
  subscribeSync(token, value => { state = value })
  await vi.advanceTimersByTimeAsync(0)
  for (const reason of ['quiet', 'save', 'retry', 'foreground'] as const) { requestSync(token, reason); await vi.advanceTimersByTimeAsync(1000) }
