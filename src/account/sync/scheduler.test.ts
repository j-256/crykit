it.each(['save', 'quiet'] as const)('pending%sSupersedesOrdinaryPollingWithoutLosingSavePriority', async reason => {
  vi.useFakeTimers(); vi.setSystemTime(0)
  vi.stubGlobal('document', Object.assign(new EventTarget(), { visibilityState: 'visible' })); vi.stubGlobal('window', new EventTarget()); vi.stubGlobal('navigator', { onLine: true })
  const token = installProfile(accountId, new Uint8Array(32), { accountId, username: 'synthetic', sessionId: accountId, deviceId: accountId, csrf: 'secret', authenticatedAt: 1 })
  let release!: () => void
  const held = new Promise<void>(resolve => { release = resolve }), calls: number[] = []
  attachSyncScheduler(token, async () => { calls.push(Date.now()); if (calls.length === 1) await held; return { state: 'synced', moreWork: false } })
  await vi.advanceTimersByTimeAsync(0)
  requestSync(token, reason)
  if (reason === 'save') requestSync(token, 'quiet')
  release(); await vi.advanceTimersByTimeAsync(0)
  if (reason === 'quiet') { expect(calls).toEqual([0]); await vi.advanceTimersByTimeAsync(QUIET_UPLOAD_MS) }
  expect(calls).toEqual([0, reason === 'save' ? 0 : QUIET_UPLOAD_MS])
})
